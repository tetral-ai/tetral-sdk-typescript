// Writes the generated part of COMPATIBILITY.md: what the SDK's upstream types
// offer that Engine does not serve, found by comparing the upstream spec the
// types are generated from with the SDK's copy of Engine's OpenAPI file.
//
//   node scripts/compatibility-list.cjs           rewrite the part in place
//   node scripts/compatibility-list.cjs --check   fail when it is out of date

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const root = path.resolve(__dirname, '..');
const documentPath = path.join(root, 'COMPATIBILITY.md');
const START = '<!-- generated by scripts/compatibility-list.cjs: start -->';
const END = '<!-- generated by scripts/compatibility-list.cjs: end -->';
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function readInputs() {
  return {
    upstream: JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(root, 'scripts/mock-spec.json.gz')))),
    engine: JSON.parse(fs.readFileSync(path.join(root, 'api/engine-v1.openapi.json'), 'utf8')),
    source: JSON.parse(fs.readFileSync(path.join(root, 'api/engine-v1.source.json'), 'utf8')),
  };
}

function resolve(document, schema) {
  let at = schema;
  const seen = new Set();
  while (at && typeof at === 'object' && typeof at.$ref === 'string') {
    if (seen.has(at.$ref)) throw new Error(`$ref loop at ${at.$ref}`);
    seen.add(at.$ref);
    at = at.$ref
      .slice(2)
      .split('/')
      .reduce((node, token) => node[token.replace(/~1/g, '/').replace(/~0/g, '~')], document);
  }
  return at;
}

/**
 * What a schema allows, one level deep: its object shapes (each with the
 * values its `type` property is fixed to), its string values, its array items,
 * whether it takes null, and whether it takes anything else.
 */
function shapes(
  document,
  schema,
  into = {
    objects: [],
    values: new Set(),
    anyString: false,
    items: [],
    null: false,
    other: false,
    any: false,
  },
) {
  const at = resolve(document, schema);
  if (!at || typeof at !== 'object') return into;
  for (const key of ['oneOf', 'anyOf']) {
    if (Array.isArray(at[key]) && !at.properties) {
      for (const part of at[key]) shapes(document, part, into);
      return into;
    }
  }
  if (Array.isArray(at.allOf)) {
    const parts = at.allOf.map((part) => shapes(document, part));
    if (parts.every((part) => part.objects.length === 1)) {
      into.objects.push({
        properties: Object.assign({}, ...parts.map((part) => part.objects[0].properties)),
        tags: parts.map((part) => part.objects[0].tags).find((tags) => tags) ?? null,
        closed: parts.some((part) => part.objects[0].closed),
        required: parts.flatMap((part) => part.objects[0].required),
      });
    } else {
      for (const part of at.allOf) shapes(document, part, into);
    }
    return into;
  }
  for (const type of Array.isArray(at.type) ? at.type : [at.type]) {
    if (type === 'object' || (type === undefined && at.properties)) {
      const properties = at.properties ?? {};
      const tag = properties.type && resolve(document, properties.type);
      const tags =
        tag && tag.const !== undefined ? [tag.const]
        : tag && Array.isArray(tag.enum) ? tag.enum
        : null;
      into.objects.push({
        properties,
        tags,
        closed: at.additionalProperties === false,
        required: at.required ?? [],
      });
    } else if (type === 'array') {
      if (at.items) into.items.push(at.items);
    } else if (type === 'string' || (type === undefined && (at.enum || at.const !== undefined))) {
      if (at.const !== undefined) into.values.add(at.const);
      else if (Array.isArray(at.enum)) for (const value of at.enum) into.values.add(value);
      else into.anyString = true;
    } else if (type === 'null') {
      into.null = true;
    } else {
      // A number, a boolean, or a schema that states no type and so takes anything.
      into.other = true;
      if (type === undefined) into.any = true;
    }
  }
  return into;
}

/**
 * Collects into `found` each place where the upstream schema allows what
 * Engine's schema does not, as `[place, kind, item]` in JSON: a `member` of a
 * union, a `value` of a string, a `field`, `null` where only null is taken,
 * and, in a request body, the value `null` where Engine takes none and a field
 * that is `required` by Engine alone.
 */
function compare(documents, upstreamSchema, engineSchema, at, found, stack = [], demands = at === 'body') {
  // A schema that holds itself is compared once inside itself, then no deeper.
  const upstreamAt = resolve(documents.upstream, upstreamSchema);
  if (stack.filter((one) => one === upstreamAt).length > 1) return;
  const visited = [...stack, upstreamAt];

  const ours = shapes(documents.upstream, upstreamSchema);
  const theirs = shapes(documents.engine, engineSchema);

  if (theirs.values.size > 0 && !theirs.anyString) {
    for (const value of ours.values) {
      if (!theirs.values.has(value)) found.add(JSON.stringify([at, 'value', value]));
    }
  }
  if (ours.items.length > 0 && theirs.items.length > 0) {
    compare(documents, { anyOf: ours.items }, { anyOf: theirs.items }, `${at}[]`, found, visited, demands);
  }
  const takes = (side) =>
    side.objects.length + side.values.size + side.items.length > 0 || side.anyString || side.other;
  if (theirs.null && !takes(theirs)) {
    if (takes(ours)) found.add(JSON.stringify([at, 'null', '']));
    return;
  }
  // In a request, `null` where Engine takes a value and no null.
  if (demands && ours.null && !theirs.null && !theirs.any) found.add(JSON.stringify([at, 'value', 'null']));
  if (ours.objects.length > 0 && theirs.objects.length === 0) return;
  const tagged = theirs.objects.some((shape) => shape.tags);
  for (const shape of ours.objects) {
    for (const tag of shape.tags ?? [null]) {
      const candidates =
        tag === null || !tagged ? theirs.objects : theirs.objects.filter((one) => one.tags?.includes(tag));
      if (candidates.length === 0) {
        found.add(JSON.stringify([at, 'member', tag]));
        continue;
      }
      const here = tag === null || !tagged ? at : `${at}<${tag}>`;
      for (const [name, property] of Object.entries(shape.properties)) {
        // The values of `type` are the members compared here.
        if (name === 'type' && shape.tags) continue;
        const holders = candidates.filter((one) => name in one.properties);
        if (
          demands &&
          !shape.required.includes(name) &&
          candidates.every((one) => one.required.includes(name))
        ) {
          found.add(JSON.stringify([`${here}.${name}`, 'required', '']));
        }
        if (holders.length === 0) {
          if (candidates.every((one) => one.closed))
            found.add(JSON.stringify([`${here}.${name}`, 'field', '']));
          continue;
        }
        compare(
          documents,
          property,
          { anyOf: holders.map((one) => one.properties[name]) },
          `${here}.${name}`,
          found,
          visited,
          demands,
        );
      }
    }
  }
}

function parameters(document, operation, place) {
  return (operation.parameters ?? [])
    .map((parameter) => resolve(document, parameter))
    .filter((parameter) => parameter.in === place);
}

function jsonSchema(content) {
  const body = content?.['application/json'] ?? content?.['multipart/form-data'];
  return body?.schema;
}

/**
 * Engine's request body, with a form field that takes several parts under the
 * name the upstream spec gives it: Engine's file writes the field as it is
 * sent, `files[]`, and the upstream spec writes the list, `files`.
 */
function takenSchema(engine, content) {
  const schema = jsonSchema(content);
  if (!schema || !content['multipart/form-data']) return schema;
  const form = resolve(engine, schema);
  const plain = (name) => name.replace(/\[\]$/, '');
  return {
    ...form,
    properties: Object.fromEntries(
      Object.entries(form.properties ?? {}).map(([name, property]) => [plain(name), property]),
    ),
    required: (form.required ?? []).map(plain),
  };
}

/** The schema of a successful answer; a stream's events as one union. */
function answerSchema(operation) {
  for (const [status, answer] of Object.entries(operation.responses ?? {})) {
    if (!status.startsWith('2') || !answer.content) continue;
    const events = answer.content['text/event-stream']?.['x-events'];
    if (events) return { anyOf: Object.values(events) };
    const schema = jsonSchema(answer.content);
    if (schema) return schema;
  }
  return undefined;
}

function matches(pattern, pathname) {
  const expression = pattern
    .split('*')
    .map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&'))
    .join('.*');
  return new RegExp(`^${expression}$`).test(pathname);
}

function collect() {
  const documents = readInputs();
  const { upstream, engine, source } = documents;

  // The upstream spec writes a beta operation as `/path?beta=true`.
  const offered = new Map();
  for (const [template, item] of Object.entries(upstream.paths)) {
    const [pathname, query] = template.split('?');
    for (const method of METHODS) {
      if (!item[method]) continue;
      const key = `${method.toUpperCase()} ${pathname}`;
      const entry = offered.get(key) ?? { method, pathname };
      entry[query ? 'beta' : 'plain'] = item[method];
      offered.set(key, entry);
    }
  }

  const refused = [];
  const unrouted = [];
  const betaOnly = [];
  const requests = new Map();
  const answers = new Map();
  const note = (map, finding, name) => map.set(finding, [...(map.get(finding) ?? []), name]);

  for (const [name, entry] of [...offered].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const served = engine.paths[entry.pathname]?.[entry.method];
    if (!served) {
      const unsupported = engine['x-undeclared-paths'].unsupported.some((pattern) =>
        matches(pattern, entry.pathname),
      );
      (unsupported ? refused : unrouted).push(name);
      continue;
    }
    const servedQuery = parameters(engine, served, 'query');
    if (entry.plain && servedQuery.some((one) => one.name === 'beta' && one.required)) betaOnly.push(name);

    const operation = entry.beta ?? entry.plain;
    if (served['x-closed-query']) {
      for (const parameter of parameters(upstream, operation, 'query')) {
        if (!servedQuery.some((one) => one.name === parameter.name)) {
          note(requests, JSON.stringify([`query ${parameter.name}`, 'field', '']), name);
        }
      }
    }
    for (const parameter of parameters(upstream, operation, 'query')) {
      const other = servedQuery.find((one) => one.name === parameter.name);
      if (!other?.schema || !parameter.schema) continue;
      const found = new Set();
      compare(documents, parameter.schema, other.schema, `query ${parameter.name}`, found);
      for (const finding of found) note(requests, finding, name);
    }
    const sent = jsonSchema(operation.requestBody?.content);
    const taken = served.requestBody && takenSchema(engine, served.requestBody.content);
    if (sent && taken) {
      const found = new Set();
      compare(documents, sent, taken, 'body', found);
      for (const finding of found) note(requests, finding, name);
    }
    const given = answerSchema(operation);
    const answered = answerSchema(served);
    if (given && answered) {
      const found = new Set();
      compare(documents, given, answered, 'answer', found);
      for (const finding of found) note(answers, finding, name);
    }
  }
  return { source, refused, unrouted, betaOnly, requests, answers };
}

function operationsByPath(names) {
  const byPath = new Map();
  for (const name of names) {
    const [method, pathname] = name.split(' ');
    byPath.set(pathname, [...(byPath.get(pathname) ?? []), method]);
  }
  return [...byPath]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([pathname, methods]) => `- \`${pathname}\`: ${methods.sort().join(', ')}`);
}

/**
 * One line per place and kind: the members or values found there, and the
 * operations they were found on. An item of a list page reads as the answer
 * itself, so a list and a read of the same thing share a line.
 */
function findings(map, wanted = () => true) {
  // First each thing found, with every operation it was found on.
  const found = new Map();
  for (const [finding, names] of map) {
    const [at, kind, item] = JSON.parse(finding);
    if (!wanted(kind)) continue;
    const key = JSON.stringify([at.replace(/^answer\.data\[\]/, 'answer'), kind, item]);
    found.set(key, new Set([...(found.get(key) ?? []), ...names]));
  }
  // Then one line per place, kind and set of operations.
  const lines = new Map();
  for (const [key, names] of found) {
    const [place, kind, item] = JSON.parse(key);
    const where = [...names].sort();
    const lineKey = JSON.stringify([place, kind, where]);
    const line = lines.get(lineKey) ?? { place, kind, items: [], where };
    if (item !== '') line.items.push(item);
    lines.set(lineKey, line);
  }
  const code = (texts) => texts.map((text) => `\`${text}\``).join(', ');
  return [...lines.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([, { place, kind, items, where }]) => {
      const what =
        kind === 'member' ? ` ${items.length > 1 ? 'members' : 'member'} ${code(items.sort())}`
        : kind === 'value' ? ` ${items.length > 1 ? 'values' : 'value'} ${code(items.sort())}`
        : kind === 'null' ? ' other than `null`'
        : '';
      return `- \`${place}\`${what}: ${code(where)}`;
    });
}

/** The generated part, from its start marker to its end marker. */
function generate() {
  const { source, refused, unrouted, betaOnly, requests, answers } = collect();
  return [
    START,
    '',
    'This list is generated in the SDK repository by `scripts/compatibility-list.cjs`. It compares the',
    "upstream spec that the SDK's types are generated from with Engine's OpenAPI file at Engine commit",
    `\`${source.commit}\`. A place is written as a path into the request body or`,
    'the answer: `[]` is an item of a list, `<name>` the object whose `type` is `name`. Where the fork',
    'writes a type by hand (§2), that type may no longer offer what a line names.',
    '',
    '#### Operations Engine refuses as unsupported',
    '',
    'Engine answers 400 `invalid_request_error`.',
    '',
    ...operationsByPath(refused),
    '',
    '#### Operations Engine does not have',
    '',
    'Engine answers 404, or 405 where it has the path with other methods only.',
    '',
    ...operationsByPath(unrouted),
    '',
    '#### Operations Engine serves only with `beta=true`',
    '',
    'The SDK also has these without the `beta=true` query; Engine requires it.',
    '',
    ...operationsByPath(betaOnly),
    '',
    '#### Request parameters, fields and values Engine refuses',
    '',
    ...findings(requests, (kind) => kind !== 'required'),
    '',
    '#### Request fields Engine requires',
    '',
    'The upstream types leave these optional; Engine refuses a request without them.',
    '',
    ...findings(requests, (kind) => kind === 'required'),
    '',
    '#### Answer and event members, fields and values Engine never sends',
    '',
    ...findings(answers),
    '',
    END,
  ].join('\n');
}

/** The committed document with its generated part replaced by `part`. */
function withGenerated(document, part) {
  const start = document.indexOf(START);
  const end = document.indexOf(END);
  if (start < 0 || end < start) throw new Error('COMPATIBILITY.md has no generated part');
  return document.slice(0, start) + part + document.slice(end + END.length);
}

module.exports = { compare, generate, takenSchema, withGenerated, documentPath };

if (require.main === module) {
  const committed = fs.readFileSync(documentPath, 'utf8');
  const current = withGenerated(committed, generate());
  if (process.argv.includes('--check')) {
    if (current !== committed) {
      console.error('COMPATIBILITY.md is out of date: run `node scripts/compatibility-list.cjs`.');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(documentPath, current);
  }
}
